const fs = require('fs');
const path = require('path');
const raw = process.env.CONDITIONAL_OK_API_URL || 'https://oranganman.site/v1';
const url = new URL(raw);
if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash) {
  throw new Error('CONDITIONAL_OK_API_URL must be an HTTPS URL without credentials/query/hash');
}
const dir = path.join(__dirname, '../src/config');
fs.mkdirSync(dir, {recursive:true});
fs.writeFileSync(path.join(dir,'runtime.generated.ts'), `// Generated by scripts/configure.cjs; no secrets belong here.\nexport const API_BASE_URL = ${JSON.stringify(raw.replace(/\/$/,''))};\nexport const INVITE_BASE_URL = ${JSON.stringify(url.origin)};\n`);
